"""
Data models and enumeration types for Infomatirx.
Uses standard Python library (dataclasses, enum) to ensure zero external dependencies.
"""

from dataclasses import dataclass, field, asdict
from datetime import datetime, timezone
from enum import Enum
from typing import Optional, Dict, Any


class TaskStatus(str, Enum):
    """Lifecycle states of a task across the software development lifecycle."""
    BACKLOG = "BACKLOG"
    DESIGN = "DESIGN"
    DEV = "DEV"
    TEST = "TEST"
    WAITING_APPROVAL = "WAITING_APPROVAL"
    RELEASED = "RELEASED"
    CANCELLED = "CANCELLED"


class AgentRole(str, Enum):
    """Known agent roles and human actors in Infomatirx."""
    ORCHESTRATOR = "Orchestrator"
    DESIGNBOT = "DesignBot"
    DEVBOT = "DevBot"
    TESTBOT = "TestBot"
    RELEASEBOT = "ReleaseBot"
    HUMAN = "Human"


class EventType(str, Enum):
    """
    Categorization of recorded actions.
    Crucially distinguishes between simulated LLM roleplay messages and
    actual system/tool executions.
    """
    SIMULATED_MESSAGE = "SIMULATED_MESSAGE"  # Natural language message/thought from an agent
    TOOL_EXECUTION = "TOOL_EXECUTION"        # Real command or tool call run on the host machine
    STATUS_CHANGE = "STATUS_CHANGE"          # Transition between task pipeline stages
    ARTIFACT_CREATED = "ARTIFACT_CREATED"    # Tangible file created (spec, code, test report)
    HUMAN_APPROVAL = "HUMAN_APPROVAL"        # Manual sign-off or decision by the human operator
    ERROR = "ERROR"                          # Failure, crash, or validation error


class ArtifactType(str, Enum):
    """Types of deliverables generated during a task."""
    SPEC = "SPEC"                    # Product requirement document / wireframes (DesignBot)
    CODE_DIFF = "CODE_DIFF"          # Patch or list of files modified (DevBot)
    TEST_REPORT = "TEST_REPORT"      # Test plan, run logs, pass/fail stats (TestBot)
    RELEASE_NOTES = "RELEASE_NOTES"  # Changelog, README update, release checklist (ReleaseBot)


def current_iso_time() -> str:
    """Helper to return current UTC timestamp in ISO 8601 format."""
    return datetime.now(timezone.utc).isoformat()


@dataclass
class Task:
    """Represents a work item moving through the Infomatirx pipeline."""
    id: str
    title: str
    description: str
    status: TaskStatus = TaskStatus.BACKLOG
    assigned_role: AgentRole = AgentRole.DESIGNBOT
    created_at: str = field(default_factory=current_iso_time)
    updated_at: str = field(default_factory=current_iso_time)

    def to_dict(self) -> Dict[str, Any]:
        """Convert task to dictionary representation."""
        data = asdict(self)
        data["status"] = self.status.value if isinstance(self.status, TaskStatus) else self.status
        data["assigned_role"] = self.assigned_role.value if isinstance(self.assigned_role, AgentRole) else self.assigned_role
        return data


@dataclass
class Event:
    """An immutable audit log entry recording every action, message, or execution."""
    id: Optional[int]
    task_id: str
    actor: str
    event_type: EventType
    content: str
    metadata: Dict[str, Any] = field(default_factory=dict)
    timestamp: str = field(default_factory=current_iso_time)

    def to_dict(self) -> Dict[str, Any]:
        """Convert event to dictionary representation."""
        return {
            "id": self.id,
            "task_id": self.task_id,
            "actor": self.actor,
            "event_type": self.event_type.value if isinstance(self.event_type, EventType) else self.event_type,
            "content": self.content,
            "metadata": self.metadata,
            "timestamp": self.timestamp,
        }


@dataclass
class Artifact:
    """A tangible deliverable file generated by an agent and saved on disk."""
    id: str
    task_id: str
    artifact_type: ArtifactType
    filename: str
    file_path: str
    created_by: str
    created_at: str = field(default_factory=current_iso_time)

    def to_dict(self) -> Dict[str, Any]:
        """Convert artifact to dictionary representation."""
        return {
            "id": self.id,
            "task_id": self.task_id,
            "artifact_type": self.artifact_type.value if isinstance(self.artifact_type, ArtifactType) else self.artifact_type,
            "filename": self.filename,
            "file_path": self.file_path,
            "created_by": self.created_by,
            "created_at": self.created_at,
        }
